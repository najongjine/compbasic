def write_files():
    expected = []
    for name, biography, quotes in DATA:
        folder = ROOT / name
        folder.mkdir(exist_ok=True)
        bio_text = (
            f"{name}\n"
            f"{'=' * len(name)}\n\n"
            f"{biography}\n\n"
            "※ 연도와 고대 인물의 생애 세부 사항은 연구 자료에 따라 조금 다를 수 있습니다.\n"
        )
        quote_lines = [
            f"{name} 대표 명언과 해설",
            "=" * (len(name) + 11),
            "",
            f"수록 수: {len(quotes)}개 (요청한 상한 100개 이내)",
            "번역 문구는 판본에 따라 달라질 수 있습니다. '요지' 또는 '원전 불명' 표시는 인용 성격을 확인해 사용하세요.",
            "",
        ]
        for number, (quote, source, explanation) in enumerate(quotes, 1):
            quote_lines.extend([
                f"{number}. “{quote}”",
                f"   출처/전승: {source}",
                f"   해설: {explanation}",
                "",
            ])
        (folder / "biograhpy.txt").write_text(bio_text, encoding="utf-8-sig", newline="\r\n")
        (folder / "명언.txt").write_text("\n".join(quote_lines), encoding="utf-8-sig", newline="\r\n")
        expected.extend([folder / "biograhpy.txt", folder / "명언.txt"])

    assert len(DATA) == 30, f"철학자 수 오류: {len(DATA)}"
    assert len(expected) == 60 and all(path.is_file() for path in expected)
    assert all(len(quotes) <= 100 for _, _, quotes in DATA)
    print(f"완료: 철학자 {len(DATA)}명, 파일 {len(expected)}개, 명언 {sum(len(q) for _, _, q in DATA)}개")


if __name__ == "__main__":
    write_files()
